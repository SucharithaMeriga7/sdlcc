/*==============================================================
Object Name    : TRANSFORM_CLEAN
Purpose        : Remove null and duplicate records from the
                 CUSTOMER and ORDER landing tables to ensure
                 data quality before downstream transformations.
Generated By   : SDLC_DEVELOPER
==============================================================*/

---------------------------------------------------------
-- SECTION 1
-- Purpose: Remove null records from CUSTOMER table
---------------------------------------------------------

DELETE FROM IDEA_2_DB.PUBLIC.CUSTOMER
WHERE CUSTID   IS NULL
   OR NAME     IS NULL
   OR EMAILID  IS NULL
   OR REGION   IS NULL;

---------------------------------------------------------
-- SECTION 2
-- Purpose: Remove null records from ORDER table
---------------------------------------------------------

DELETE FROM IDEA_2_DB.PUBLIC."order"
WHERE ORDERID      IS NULL
   OR CUSTID       IS NULL
   OR ITEMNAME     IS NULL
   OR PRICEPERUNIT IS NULL
   OR QTY          IS NULL
   OR ORDER_DATE   IS NULL;

---------------------------------------------------------
-- SECTION 3
-- Purpose: Remove duplicate records from CUSTOMER table
---------------------------------------------------------

CREATE OR REPLACE TEMPORARY TABLE IDEA_2_DB.PUBLIC.CUSTOMER_DEDUP AS
SELECT *
FROM IDEA_2_DB.PUBLIC.CUSTOMER
QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTID ORDER BY NAME) = 1;

TRUNCATE TABLE IDEA_2_DB.PUBLIC.CUSTOMER;

INSERT INTO IDEA_2_DB.PUBLIC.CUSTOMER
SELECT * FROM IDEA_2_DB.PUBLIC.CUSTOMER_DEDUP;

---------------------------------------------------------
-- SECTION 4
-- Purpose: Remove duplicate records from ORDER table
---------------------------------------------------------

CREATE OR REPLACE TEMPORARY TABLE IDEA_2_DB.PUBLIC.ORDER_DEDUP AS
SELECT *
FROM IDEA_2_DB.PUBLIC."order"
QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDERID ORDER BY ORDER_DATE DESC) = 1;

TRUNCATE TABLE IDEA_2_DB.PUBLIC."order";

INSERT INTO IDEA_2_DB.PUBLIC."order"
SELECT * FROM IDEA_2_DB.PUBLIC.ORDER_DEDUP;

-- FILE: 04_transform_ordersummary.sql
/*==============================================================
Object Name    : TRANSFORM_ORDERSUMMARY
Purpose        : Join CUSTOMER and ORDER tables and populate
                 the ORDERSUMMARY table with enriched order
                 records including computed TOTALAMOUNT.
Generated By   : SDLC_DEVELOPER
==============================================================*/

---------------------------------------------------------
-- SECTION 1
-- Purpose: Truncate ORDERSUMMARY before reload
---------------------------------------------------------

TRUNCATE TABLE IDEA_2_DB.PUBLIC.ORDERSUMMARY;

---------------------------------------------------------
-- SECTION 2
-- Purpose: Insert joined and enriched data into ORDERSUMMARY
--          Using INNER JOIN to ensure referential integrity:
--          only orders with a matching CUSTID in CUSTOMER
--          are included (no orphan records).
---------------------------------------------------------

INSERT INTO IDEA_2_DB.PUBLIC.ORDERSUMMARY (
    ORDERID,
    CUSTID,
    NAME,
    ITEMNAME,
    PRICEPERUNIT,
    QTY,
    TOTALAMOUNT,
    ORDER_DATE,
    STARTDATE,
    ENDDATE,
    ISACTIVE
)
SELECT
    o.ORDERID,
    o.CUSTID,
    c.NAME,
    o.ITEMNAME,
    o.PRICEPERUNIT,
    o.QTY,
    o.PRICEPERUNIT * o.QTY AS TOTALAMOUNT,
    o.ORDER_DATE,
    o.STARTDATE,
    o.ENDDATE,
    o.ISACTIVE
FROM IDEA_2_DB.PUBLIC."order" o
INNER JOIN IDEA_2_DB.PUBLIC.CUSTOMER c
    ON o.CUSTID = c.CUSTID;

---------------------------------------------------------
-- SECTION 3
-- Purpose: Safety net - Remove any orphan records from
--          ORDERSUMMARY where CUSTID does not exist in CUSTOMER
---------------------------------------------------------

DELETE FROM IDEA_2_DB.PUBLIC.ORDERSUMMARY os
WHERE NOT EXISTS (
    SELECT 1
    FROM IDEA_2_DB.PUBLIC.CUSTOMER c
    WHERE c.CUSTID = os.CUSTID
);

-- FILE: 05_transform_scd2.sql
/*==============================================================
Object Name    : TRANSFORM_SCD2
Purpose        : Implement SCD Type 2 logic on the CUSTOMER_SCD2
                 table to track historical changes in customer
                 dimension attributes.
Generated By   : SDLC_DEVELOPER
==============================================================*/

---------------------------------------------------------
-- SECTION 1
-- Purpose: MERGE into CUSTOMER_SCD2 using SCD Type 2 logic
--          - When a matching current record exists and attributes
--            have changed, expire the old record and insert new.
--          - When no match exists, insert the new record.
---------------------------------------------------------

MERGE INTO IDEA_2_DB.PUBLIC.CUSTOMER_SCD2 AS tgt
USING IDEA_2_DB.PUBLIC.CUSTOMER AS src
ON tgt.CUSTID = src.CUSTID AND tgt.IS_CURRENT = TRUE
WHEN MATCHED AND (
    tgt.NAME    != src.NAME
    OR tgt.EMAILID != src.EMAILID
    OR tgt.REGION  != src.REGION
) THEN UPDATE SET
    tgt.IS_CURRENT    = FALSE,
    tgt.EFFECTIVE_TO  = CURRENT_DATE()
WHEN NOT MATCHED THEN INSERT (
    CUSTID,
    NAME,
    EMAILID,
    REGION,
    IS_CURRENT,
    EFFECTIVE_FROM,
    EFFECTIVE_TO
) VALUES (
    src.CUSTID,
    src.NAME,
    src.EMAILID,
    src.REGION,
    TRUE,
    CURRENT_DATE(),
    NULL
);

---------------------------------------------------------
-- SECTION 2
-- Purpose: Insert the new current version for changed records
---------------------------------------------------------

INSERT INTO IDEA_2_DB.PUBLIC.CUSTOMER_SCD2 (
    CUSTID,
    NAME,
    EMAILID,
    REGION,
    IS_CURRENT,
    EFFECTIVE_FROM,
    EFFECTIVE_TO
)
SELECT
    src.CUSTID,
    src.NAME,
    src.EMAILID,
    src.REGION,
    TRUE,
    CURRENT_DATE(),
    NULL
FROM IDEA_2_DB.PUBLIC.CUSTOMER src
INNER JOIN IDEA_2_DB.PUBLIC.CUSTOMER_SCD2 tgt
    ON src.CUSTID = tgt.CUSTID
    AND tgt.IS_CURRENT = FALSE
    AND tgt.EFFECTIVE_TO = CURRENT_DATE()
WHERE NOT EXISTS (
    SELECT 1
    FROM IDEA_2_DB.PUBLIC.CUSTOMER_SCD2 chk
    WHERE chk.CUSTID = src.CUSTID
      AND chk.IS_CURRENT = TRUE
);

