---------------------------------------------------------
-- SECTION 2
-- Purpose: Aggregate and insert total spend per customer per order date
---------------------------------------------------------

INSERT INTO IDEA_2_DB.PUBLIC.CUSTOMERAGGREGATESPEND (
    NAME,
